#!/usr/bin/env bash
# AI 味自检 —— 用法: ai-voice-check.sh article.md
set -uo pipefail
F="${1:?用法: ai-voice-check.sh <file.md>}"
[ -f "$F" ] || { echo "找不到文件: $F" >&2; exit 1; }

HIT=0
scan() {  # scan "类别名" "grep -E 正则"
  local label="$1" pat="$2" out
  out=$(grep -nE "$pat" "$F" || true)
  [ -z "$out" ] && return
  echo "── $label"
  echo "$out" | sed 's/^/   /'
  echo
  HIT=$((HIT + $(printf '%s\n' "$out" | wc -l | tr -d ' ')))
}

echo "中文表达编辑线索: $F"
echo "以下为上下文复核提示，不要求清零命中；引文、关键条件和用户保留表达按实际作用判断。"
echo

scan "① 反转对举（检查是否重复表达同一意思）" \
  '不是.{0,12}而是|不只是.{0,12}[，,]?\s*(是|而是)|不在.{0,10}而在|真正的.{0,10}不是|从来不是|并不是.{0,12}而是'

scan "② 元评论 / 讲解腔起手（检查是否提供新信息）" \
  '翻译过来|停下来想|我想让你|这里是我|道理讲完|我说这些|真拆开看|真正关键的|你要先明白|一次性(说清|说透|讲清)|先问问是不是|先讲清楚|值得一提'

scan "②₅ 价值排序宣告（检查是否有具体依据）" \
  '最值钱的|最关键的是|最重要的一点|最狠的是|真正值钱的|核心只有一条|最要紧的是'

scan "②₈ 假反应 / 替读者代言" \
  '出乎意料|没想到|真没想到|所有[一-鿿]{0,4}都担心|你可能会好奇|相信很多人|大家都知道'

scan "③ 收尾与判断（检查是否由本篇内容支持）" \
  '比.{2,15}强得多|是两回事|这就是[^。]{0,20}。|性质(就)?变了|性质改了|从来没有人|说到底|归根结底'

scan "④ 总结腔标签（检查是否只是引导语）" \
  '一句话总结|简而言之|概括来说|综上所述|总而言之|本质上|换句话说|也就是说|值得注意的是|需要说明的是'

scan "⑤ 开篇套话" \
  '随着.{0,10}的?不断发展|在当今|近年来|越来越多的关注|作为一名'

scan "⑥ 结构自报（检查与本段信息的关系）" \
  '接下来我们|下面进入|先铺一张|还有一层|再多说一句|这篇文章(要|将)'

scan "⑦ 机械列举" \
  '首先.{0,30}其次|第一[，,、].{0,40}第二[，,、]'

scan "⑦₅ 标题自证体 / 方法承诺体" \
  '我自己.{0,4}了一遍|我亲自|实测[0-9一二三四五六七八九十]+[天周月]|一文读懂|保姆级|说透了|全网最全|^#.*——'

scan "⑧ 翻译腔物理动词" \
  '接住|击穿|锋利|扛住|打穿|不崩|不爆'

scan "⑨ 正式化用词（根据受众与文本类型判断）" \
  '非常|极其|例如|拥有|购买|呈现|进行[一-鿿]{2}|致力于|无需|均可|皆为'

scan "⑩ 互联网黑话" \
  '赋能|抓手|闭环|沉淀|对齐|拉通|打通|链路|心智|调性|势能|兜底|颗粒度|触达|复盘|赛道|底层逻辑|方法论'

scan "⑪ 科技媒体腔（AI 选题专属坑）" \
  '重磅|炸裂|炸了|刚刚[，,]|一夜之间|彻底改变|宣告死亡|时代结束|狂飙|据悉|业内人士表示|有消息称|知情人士'

scan "⑫ 自证与防御写法（检查是否真的影响读者理解）" \
  '这就有意思了|变化也很具体|不能简单等同|仅供参考|本文只讨论|不代表.{0,12}已经'

echo "── 密度统计"
python3 - "$F" <<'PY'
import re, sys
t = open(sys.argv[1], encoding='utf-8').read()
body = t.split('---', 2)[2] if t.startswith('---') else t
cn   = len(re.findall(r'[一-鿿]', body))
bold = len(re.findall(r'\*\*[^*\n]+\*\*', body))
dash = body.count('——')
excl = body.count('！')
quot = len(re.findall(r'[“”"]', body))
def flag(v, cap): return "  ← 核对" if v > cap else ""
print(f"   中文字数 {cn}")
print(f"   加粗     {bold}  (结合篇幅与当前版式判断)")
print(f"   破折号   {dash}  (检查是否影响自然阅读)")
print(f"   感叹号   {excl}  (检查是否符合本篇语气)")
print(f'   弯引号   {quot}  (应为 0，正文用「」){flag(quot,0)}')
PY

echo
if [ "$HIT" -eq 0 ]; then
  echo "本次词形扫描未命中。仍需通读全文，检查故事、信息与口语是否成立。"
else
  echo "共命中 $HIT 处编辑线索。逐项结合上下文判断；扫描结果不代表文风验收。"
fi
